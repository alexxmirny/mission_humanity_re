#!/usr/bin/env python3
"""Generate ovftest's real-save MHOV fixture header (patching:PT-CAP9-U7a).

    python tools/gen_ovf_fixtures.py --sav <8-ayatus-rl-2.sav> [--out src/mh_dll/mh_nettest/ovf_rc2_blob.gen.h]
    python tools/lint_repo.py --fix        # the emitted header is inside src/mh_dll: clang-format owns its final layout

WHY. ovftest has to prove that a RAISED save written by a SHIPPED build (the user's v0.2.2-rc2 playtest save, MHOV version 1, layout fingerprint
0x2bdef41f, 8 records) still passes check() and applies byte-exact after the MHOV v2 rework. The blob must be bytes that build WROTE, not bytes
this codec produced, so the header carries it verbatim, cut out of the container: the planet member file ends in `[MHOV blob][u32 len]['MHOF']`
and the container embeds the member verbatim, so the blob is found by scanning for the footer (the same walk ovf_save.cpp's read_footer does).

The second real fixture, tools/uiscripts/saves/capovf.sav (1305 records, 225 KB), is too big to inline; ovftest finds it by walking up from
the working directory and cuts the same blob out at run time (see ovf_selftest.cpp, real_sav_blob()).
"""

from __future__ import annotations

import argparse
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
MAGIC_OV = b"MHOV"
MAGIC_OF = b"MHOF"


def find_blobs(data: bytes):
    """Every (start, length) of an MHOV blob that ends in a valid MHOF footer."""
    out = []
    i = -1
    while True:
        i = data.find(MAGIC_OF, i + 1)
        if i < 0:
            return out
        if i < 4:
            continue
        (ln,) = struct.unpack("<I", data[i - 4 : i])
        st = i - 4 - ln
        if st >= 0 and data[st : st + 4] == MAGIC_OV:
            out.append((st, ln))


def render(name: str, blob: bytes) -> str:
    magic, version, nsec, body_len, fp, body_sum, records, reserved = struct.unpack(
        "<IHHIIQII", blob[:32]
    )
    rows = []
    for k in range(0, len(blob), 16):
        rows.append("    " + ", ".join("0x%02x" % b for b in blob[k : k + 16]) + ",")
    return (
        "// GENERATED by tools/gen_ovf_fixtures.py from %s -- do not hand-edit.\n"
        "//\n"
        "// The MHOV blob (version %d, %d section(s), %d record(s), layout_fp 0x%08x) a SHIPPED v0.2.2-rc2 build wrote into the user's playtest save.\n"
        "// ovftest (patching:PT-CAP9-U7a) must still check() it, apply it byte-exact and re-encode it byte-identically.\n"
        "#pragma once\n"
        "#include <cstdint>\n\n"
        "namespace ovf_fixture {\n\n"
        "inline constexpr uint32_t RC2_LEN      = %du;\n"
        "inline constexpr uint16_t RC2_VERSION  = %du;\n"
        "inline constexpr uint32_t RC2_FP       = 0x%08xu;\n"
        "inline constexpr uint32_t RC2_RECORDS  = %du;\n"
        "inline constexpr uint16_t RC2_SECTIONS = %du;\n\n"
        "inline const uint8_t RC2_BLOB[] = {\n%s\n};\n\n"
        "} // namespace ovf_fixture\n"
    ) % (name, version, nsec, records, fp, len(blob), version, fp, records, nsec, "\n".join(rows))


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--sav", required=True, help="the rc2 playtest save (8-ayatus-rl-2.sav)")
    ap.add_argument(
        "--out", default=os.path.join(REPO, "src", "mh_dll", "mh_nettest", "ovf_rc2_blob.gen.h")
    )
    a = ap.parse_args(argv)
    data = open(a.sav, "rb").read()
    blobs = find_blobs(data)
    if len(blobs) != 1:
        print(
            "gen_ovf_fixtures: expected exactly one MHOV blob in %s, found %d" % (a.sav, len(blobs))
        )
        return 1
    st, ln = blobs[0]
    text = render(os.path.basename(a.sav), data[st : st + ln])
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("gen_ovf_fixtures: wrote %s (%d bytes of blob)" % (a.out, ln))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
