#!/usr/bin/env python3
"""check_publishable.py -- fork F5A: the publishability ledger's gate.

WHAT THIS IS FOR. The public cut (F5M) has to produce a tree that is a DERIVED set, not a pile of
per-file judgement calls made on the day. `tools/data/publish_ledger.json` is that derivation: an
ordered list of rules, first-match-wins, giving every path `git ls-files` reports exactly one
disposition. This script is the half that makes the ledger falsifiable.

    publish        goes into the public tree
    withhold       does not, and is not expected to
    user_pending   does not YET -- a question (Q2..Q7) is the user's to answer; the row records
                   the recommendation and the reasoning so the answer is a yes/no, not a research
                   task. F5M cannot close while any of these remain.
    publish_after  does not YET -- a tracker item (F5B/F5C) must change the BYTES first (regenerate
                   a fixture, scrub an IP). The row flips when the file does, not when the plan does.

THE PUBLISH SET IS `disposition == publish`, NOTHING ELSE. `--publish-list` emits it; F5C proves
the build on it and F5M cuts from it.

---- WHY THE LEDGER IS ENUMERATED FROM GIT AND NOT FROM THE DOC ----

The fork inventory sec 3 was the previous ledger. It was measured four milestones ago, listed
by hand, and by HEAD it had drifted: it never held the two largest retail-byte surfaces in the tree
(191,736 expect-bytes across 40 patch manifests; 27 transcribed CRT bodies), and its verdict on the
LZW fixtures predated the user's own ruling on their source. Re-enumerating from it was the named
risk on the F5A item. So this script calls `git ls-files` every run and matches THAT against the
rules. A path the ledger has no rule for is a FAILURE -- a file added tomorrow fails closed rather
than defaulting to publishable.

---- THE THREE FALSIFIABILITY ARMS (the F4G libref_asset_dispositions precedent) ----

A declaration that cannot be proven wrong is decoration. Three arms, all in `--check`:

  1. UNCOVERED      a tracked path no rule matches            -> FAIL (the ledger cannot fall behind)
  2. DEAD RULE      a rule matching zero paths                -> FAIL (a rule cannot outlive its files)
  3. COUNT          rules account for every path git reports  -> FAIL (no silently stale path list)

and one more in `--closure`:

  4. STALE EXCEPTION  a declared closure exception that no longer reproduces -> FAIL

Arm 4 made the F5C handoff self-closing, and it worked exactly as designed: when F5C repointed
gen_lzw_fixtures.py at the committed save and flipped the `lzw-fixtures` row to `publish`, this
check went RED on the now-stale `save-selftest-lzw` exception until that row was deleted too
(2026-09-14). The ledger cannot quietly keep an excuse it no longer needs.

---- THE CLOSURE ARM: the contradiction class F5C exists for ----

The ratified done_when says a clean clone BUILDS. The publish ledger says some files stay behind.
Those two can contradict each other silently, and they did: save_selftest.cpp:21 unconditionally
`#include`s sv1_lzw_fixtures.gen.h, which the F0 ledger ruled unpublishable -- so the public tree
as specified did not compile (F5C fixed it at the source, by making the header derivable from a
committed save). Detecting this is cheap HERE and expensive later, so `--closure` scans the
PUBLISHED sources for build/run edges into non-published paths:

    C/C++   `#include "X"` lines, X resolved by path-suffix against the tracked file set
    Python  string constants (parsed with `ast`, so comments never count and docstrings are
            excluded) that name a tracked non-published path

save_selftest.cpp:21 is still the KNOWN-POSITIVE CONTROL, but no longer as a violation: F5C made
the header publishable, so `--selftest` now re-runs the detector over the REAL tree under a
SYNTHETIC ledger that withholds that one header, and requires the same real edge back at the same
real line. Phrasing it against the scanner rather than against a ledger verdict is what keeps the
control from being retired by the very fix it was watching for. `--selftest` also plants violations
of every shape in a temp tree. A scan that finds nothing and a scan that is broken look identical,
which is why the control and the plants both exist.

PROSE CITATIONS ARE NOT BUILD EDGES. A comment saying "GENERATED by tools/oneoff/...py" is F5E's  # CITATION-OK
citation re-authoring, not a compile dependency, and this detector deliberately does not see it --
that is why the C/C++ arm reads `#include` lines only and the Python arm goes through `ast`.

usage:
  python tools/check_publishable.py                 # arms 1-3 (exit 1 on violation)
  python tools/check_publishable.py --closure       # arm 4 + the build/run-edge scan
  python tools/check_publishable.py --report        # the pending summary, by question
  python tools/check_publishable.py --publish-list  # the publish set, one path per line
  python tools/check_publishable.py --publish-list --json
  python tools/check_publishable.py --selftest      # planted-violation reds + walker liveness
  python tools/check_publishable.py --public        # run INSIDE a public clone: the mirror arms
  python tools/check_publishable.py --public --closure

---- --public: THE SAME LEDGER, ASKED FROM THE OTHER SIDE (fork F5M) ----

Arms 1-3 above are written for the PRIVATE tree, and arm 2 inverts on the cut's output: there every
`withhold` rule is SUPPOSED to match nothing, so the ordinary check reports nine dead rules and a
correct public tree can never pass its own gate. `--public` asks the mirror question -- no withheld
path may be TRACKED (a leak), every `publish` rule must match at least one (a dead publish rule means
the seed dropped files), uncovered still fails -- and refuses to run on a private tree. Which tree it
is, is a declared thing, not a guess: the ledger's `_public_tree_marker` block.
"""

