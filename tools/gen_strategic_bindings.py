#!/usr/bin/env python3
"""Generate launcher metadata and registered local INI bindings from the C++ action catalog.

python tools/gen_strategic_bindings.py --write
python tools/gen_strategic_bindings.py --check

No Ghidra, compiler or game is needed. --check compares every generated byte.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
CATALOG = Path("src/mh_dll/mh_common/include/mh_strategic_bindings.def")
JSON_PATH = Path("src/launcher/src/strategic_bindings.gen.json")
INI_PATH = Path("src/mh_dll/mh_common/include/mh_strategic_ini.gen.def")
EXAMPLE_PATH = Path("src/mh_dll/mh/config/strategic_keys.example.gen.ini")
IDS_PATH = Path("src/mh_dll/mh_common/include/mh_strategic_binding_ids.gen.h")
LEGACY_PATH = Path("tools/data/strategic_bindings_v1.json")
LEGACY_DEF_PATH = Path("src/mh_dll/mh_common/include/mh_strategic_legacy.gen.def")
EXTRA_COLUMNS = "third fourth third_key fourth_key".split()
COLUMNS = {
    "ACTION": "id label_en label_ru category context kind primary alternate section key alt_key ignored_modifiers native_scan native_modifiers repeat".split(),
    "ROLE": "id label_en label_ru default section key kind".split(),
    "KEY": "token scan e0 vk".split(),
    "RESERVED": "key context reason".split(),
    "EXCLUSIVE": "left right".split(),
}


def read_catalog(path, legacy_path=None):
    result = dict(schema=2, actions=[], roles=[], keys=[], reserved=[], exclusive_roles=[])
    destinations = {
        "ACTION": "actions",
        "ROLE": "roles",
        "KEY": "keys",
        "RESERVED": "reserved",
        "EXCLUSIVE": "exclusive_roles",
    }
    seen = {key: set() for key in destinations}
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        match = re.fullmatch(r"MH_STRATEGIC_(ACTION|ROLE|KEY|RESERVED|EXCLUSIVE)\((.*)\)", line)
        if not match:
            raise ValueError(f"{path}:{number}: malformed catalog row")
        kind, payload = match.groups()
        values = json.loads("[" + payload + "]")
        columns = COLUMNS[kind]
        if kind == "ACTION":
            if len(values) == len(columns):
                values += ["none", "none", "", ""]
            columns = columns + EXTRA_COLUMNS
        if len(values) != len(columns):
            raise ValueError(f"{path}:{number}: wrong column count")
        row = dict(zip(columns, values, strict=True))
        identity = (
            tuple(values)
            if kind == "EXCLUSIVE"
            else row.get("id", row.get("token", (row.get("key"), row.get("context"))))
        )
        if identity in seen[kind]:
            raise ValueError(f"{path}:{number}: duplicate {kind}: {identity}")
        seen[kind].add(identity)
        if kind == "ACTION":
            row["repeat"] = bool(row["repeat"])
            row["alt_section"] = "keys"
            row["editable"] = row["kind"] != "fixed"
            if (
                row["kind"] not in ("event", "held", "fixed")
                or not 0 <= row["ignored_modifiers"] <= 7
            ):
                raise ValueError(f"{path}:{number}: invalid action kind/modifiers")
            row["bindings"] = [
                {
                    "section": row["section"],
                    "key": row["key"],
                    "default": row["primary"],
                },
                {
                    "section": row["alt_section"],
                    "key": row["alt_key"],
                    "default": row["alternate"],
                },
            ]
            if row["third_key"] or row["fourth_key"]:
                if not row["third_key"] or not row["fourth_key"]:
                    raise ValueError(f"{path}:{number}: incomplete extra slot keys")
                row["bindings"] += [
                    {
                        "section": "keys",
                        "key": row["third_key"],
                        "default": row["third"],
                    },
                    {
                        "section": "keys",
                        "key": row["fourth_key"],
                        "default": row["fourth"],
                    },
                ]
        if kind == "KEY":
            row["e0"] = bool(row["e0"])
            if not 1 <= row["scan"] <= 127 or not 0 <= row["vk"] <= 255:
                raise ValueError(f"{path}:{number}: invalid physical key")
        result[destinations[kind]].append(list(row.values()) if kind == "EXCLUSIVE" else row)
    expected_roles = [
        "shift_modifier",
        "patrol",
        "confirm",
        "toggle_selection",
        "select_button",
        "command_button",
    ]
    if (
        not result["actions"]
        or [row["id"] for row in result["roles"]] != expected_roles
        or not result["keys"]
    ):
        raise ValueError("catalog is missing actions, canonical roles or keys")
    legacy_file = legacy_path or ROOT / LEGACY_PATH
    legacy = json.loads(legacy_file.read_text(encoding="utf-8"))
    if (
        legacy.get("schema") != 1
        or legacy.get("catalog_identity") != 0x8BF53F69
        or len(legacy.get("actions", [])) != 79
        or len(legacy.get("roles", [])) != 9
    ):
        raise ValueError("unexpected frozen strategic-bindings v1 catalog")
    result["legacy_navigation"] = [
        {"key": action[field], "default": action[default]}
        for action in legacy["actions"]
        if action["category"] == "navigation"
        for field, default in (("key", "primary"), ("alt_key", "alternate"))
    ]
    result["legacy_shift_keys"] = [
        "role_queue",
        "role_reveal",
        "role_build_repeat",
        "role_add_selection",
    ]
    identity_bytes = json.dumps(
        result, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    result["catalog_identity"] = int.from_bytes(
        hashlib.sha256(identity_bytes).digest()[:4], "little"
    )
    return result


def ini_rows(catalog):
    """Only canonical editable bindings are persisted."""
    rows = []
    for action in catalog["actions"]:
        if not action["editable"]:
            continue
        for binding in action["bindings"]:
            # These two primary rows remain in ini_keys.def.
            if binding["section"] != "keys":
                continue
            rows.append((binding["section"], binding["key"], binding["default"], "hotkey"))
    for role in catalog["roles"]:
        rows.append((role["section"], role["key"], role["default"], role["kind"]))
    identities = [(section, key) for section, key, _, _ in rows]
    if len(set(identities)) != len(identities):
        raise ValueError("duplicate persisted binding identity")
    return rows


def outputs(catalog):
    rows = ini_rows(catalog)
    registry = ["// Generated by tools/gen_strategic_bindings.py; do not hand-edit."]
    example = [
        "; Generated local strategic bindings. Apply next start; roles are NOT global modifier/button swaps.",
        "[keys]",
    ]
    for section, key, default, kind in rows:
        options = (
            "none|Ctrl|Alt|Shift"
            if kind == "modifier"
            else "MouseLeft|MouseRight"
            if kind == "button"
            else "physical"
        )
        typ = "T_ENUM" if kind != "hotkey" else "T_HOTKEY"
        registry.append(
            f'MH_INI_KEY("{section}", "{key}", {typ}, {json.dumps(default)}, C_USER, "{section}.{key}", S_GAMEPLAY, "{options}", F_LOCAL|F_RESTART)'
        )
        example.append(f";{key}={default}")
    registry.append(
        'MH_INI_KEY("keys", "bindings_version", T_INT, "2", C_USER, '
        '"keys.bindings_version", S_GAMEPLAY, "", F_LOCAL|F_RESTART)'
    )
    example.append(";bindings_version=2")
    legacy_def = ["// Generated by tools/gen_strategic_bindings.py; import-only legacy data."]
    legacy_def += [
        f'MH_STRATEGIC_LEGACY_NAV({json.dumps(row["key"])}, {json.dumps(row["default"])})'
        for row in catalog["legacy_navigation"]
    ]
    legacy_def += [
        f"MH_STRATEGIC_LEGACY_SHIFT({json.dumps(key)})" for key in catalog["legacy_shift_keys"]
    ]
    ids = [
        "// Generated by tools/gen_strategic_bindings.py.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "namespace mh::strategic_bindings {",
        f"constexpr uint32_t catalog_identity = 0x{catalog['catalog_identity']:08x}u;",
        "enum class action_id : size_t {",
    ]
    ids += ["    " + action["id"] + "," for action in catalog["actions"]]
    ids += ["    count", "};", "} // namespace mh::strategic_bindings"]
    return {
        JSON_PATH: json.dumps(catalog, ensure_ascii=False, indent=2) + "\n",
        INI_PATH: "\n".join(registry) + "\n",
        EXAMPLE_PATH: "\n".join(example) + "\n",
        IDS_PATH: "\n".join(ids) + "\n",
        LEGACY_DEF_PATH: "\n".join(legacy_def) + "\n",
    }


def transcode_journal(raw, legacy, current):
    import struct

    def default_chord(catalog, text, ignored):
        if not text or text.lower() == "none":
            return bytes(3)
        parts = text.split("+")
        modifiers = 0
        for part in parts[:-1]:
            modifiers |= {"ctrl": 1, "alt": 2, "shift": 4}[part.lower()]
        key = next(row for row in catalog["keys"] if row["token"].lower() == parts[-1].lower())
        return bytes(
            (
                key["scan"] | (0x80 if key["e0"] else 0),
                modifiers,
                ignored,
            )
        )

    lines = raw.splitlines(keepends=True)
    matches = [index for index, line in enumerate(lines) if line.startswith(b"B ")]
    if len(matches) != 1:
        raise ValueError("journal must contain exactly one profile row")
    index = matches[0]
    parts = lines[index].rstrip(b"\r\n").split(b" ")
    if len(parts) != 3 or parts[:2] != [b"B", b"2"]:
        raise ValueError("expected journal envelope B 2")
    old = bytes.fromhex(parts[2].decode("ascii"))
    expected_header = (1, 79, 9, 0x8BF53F69)
    if len(old) != 16 + 79 * 6 + 9:
        raise ValueError("unexpected legacy profile size")
    if struct.unpack_from("<4I", old) != expected_header:
        raise ValueError("unexpected legacy profile header")

    old_actions = {
        action["id"]: old[16 + position * 6 : 16 + (position + 1) * 6]
        for position, action in enumerate(legacy["actions"])
    }
    old_roles = dict(
        zip(
            (row["id"] for row in legacy["roles"]),
            old[16 + 79 * 6 :],
            strict=True,
        )
    )

    for action in legacy["actions"]:
        if action["category"] != "navigation":
            continue
        expected = b"".join(
            default_chord(legacy, action[field], action["ignored_modifiers"])
            for field in ("primary", "alternate")
        )
        if old_actions[action["id"]] != expected:
            raise ValueError(f"custom navigation cannot be silently migrated: {action['id']}")

    shift_values = [
        old_roles[name] for name in ("queue", "reveal", "build_repeat", "add_selection")
    ]
    if len(set(shift_values)) != 1:
        raise ValueError("independent legacy Shift roles disagree")

    payload = bytearray(
        struct.pack(
            "<4I",
            2,
            len(current["actions"]),
            len(current["roles"]),
            current["catalog_identity"],
        )
    )
    for action in current["actions"]:
        if action["editable"]:
            if action["id"] not in old_actions:
                raise ValueError(f"unmapped action: {action['id']}")
            row = old_actions[action["id"]] + bytes(6)
            if action["id"] in ("chat_team", "chat_all"):
                row = old_actions[action["id"]] + old_actions[action["id"] + "_numpad"]
        else:
            row = b"".join(
                default_chord(current, binding["default"], action["ignored_modifiers"])
                for binding in action["bindings"]
            )
            row += bytes(12 - len(row))
        payload.extend(row)

    for role in current["roles"]:
        value = shift_values[0] if role["id"] == "shift_modifier" else old_roles[role["id"]]
        payload.append(value)

    ending = (
        b"\r\n"
        if lines[index].endswith(b"\r\n")
        else b"\n"
        if lines[index].endswith(b"\n")
        else b""
    )
    lines[index] = b"B 2 " + payload.hex().encode("ascii") + ending
    return b"".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--migrate-journal", type=Path)
    parser.add_argument("--journal-out", type=Path)
    args = parser.parse_args()
    if args.migrate_journal:
        if not args.journal_out:
            parser.error("--migrate-journal requires --journal-out")
        legacy = json.loads((args.root / LEGACY_PATH).read_text(encoding="utf-8"))
        current = read_catalog(args.root / CATALOG, args.root / LEGACY_PATH)
        args.journal_out.write_bytes(
            transcode_journal(args.migrate_journal.read_bytes(), legacy, current)
        )
        return 0
    if args.journal_out:
        parser.error("--journal-out requires --migrate-journal")
    generated = outputs(read_catalog(args.root / CATALOG, args.root / LEGACY_PATH))
    stale = []
    for relative, content in generated.items():
        path = args.root / relative
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        elif not path.is_file() or path.read_bytes() != content.encode("utf-8"):
            stale.append(str(relative))
    if stale:
        print("Strategic binding outputs are stale: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
