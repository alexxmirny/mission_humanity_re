"""Model <-> a split-by-meaning YAML source tree under ``mod_src/cfg/``.

This is the human-facing layer: :func:`write_tree` decompiles a
:class:`~cfgkit.parse.Model` into a directory of editable YAML files (defaults
omitted, one file per meaning-group, each object carrying an explicit ``index``
so files may be split/reordered freely), and :func:`read_tree` reads the tree
back into a Model. Compiled game output still comes from :mod:`cfgkit.emit`;
these YAML files are the *sources* you edit.

Round-trip contract: ``read_tree(write_tree(m))`` is canon-equal to ``m``.
Objects are grouped by class into files (UNIT/BUILDING further split by faction),
recombined on read and ordered by ``index`` (dense 0..N-1 per class), so cross-
file placement is purely organizational.

Phase 4 will layer the English alias table on top (identifiers here are still the
original Polish/wire names).
"""
from __future__ import annotations

import glob
import os
import shutil
from collections import Counter, defaultdict

import yaml

from . import decompile as D
from . import grammar as G
from .emit import _reverse_map, fmt_float

# top-level YAML key -> model class name
KEY2CLASS = {
    "anims": "ANIM", "weapons": "WEAPON", "units": "UNIT", "buildings": "BUILDING",
    "inventions": "PROGRESS", "upgrades": "UPGRADE", "projects": "PROJECT",
    "systems": "SYSTEM", "planets": "PLANET", "trees": "TREE", "stones": "STONE",
}
CLASS2KEY = {v: k for k, v in KEY2CLASS.items()}

_HEADER_TOP = ("# GENERATED by cfgkit — edit these sources then recompile "
               "(python -m src.formats.cfgkit.cfg_compile).\n")
_HEADER_WIRE = ("# Identifiers are the original wire names. Do NOT edit "
                "mod_src/overlay/ (that is the compiled output).\n\n")
_HEADER_ALIAS = ("# Identifiers are English aliases (see aliases.yaml); unmapped "
                 "names pass through. Do NOT edit mod_src/overlay/.\n\n")


def _faction(name: str) -> str:
    n = name.lower()
    return "alien" if "alien" in n else "human" if "human" in n else "other"


def _wire_factions(model, aliases):
    """{cls: [faction per object, in class order]} taken from the WIRE names, so
    English-aliased trees still split into alien/human/other (the English alias
    usually drops the faction word). Aliasing preserves order, so these align
    positionally with ``_objs`` on the aliased model. None when no aliases."""
    if aliases is None:
        return None
    return {cls: [_faction(r["__name__"]) for r in model.classes[cls]]
            for cls in ("UNIT", "BUILDING")}


def _dump(cfg_dir, rel, data, header):
    path = os.path.join(cfg_dir, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(header)
        # default_flow_style=None: all-scalar collections render inline
        # ({0: A_x, 1: A_y}, [zloze_a, 700]); nested ones stay block.
        yaml.safe_dump(data, f, allow_unicode=True, sort_keys=False,
                       default_flow_style=None, width=100)


def _short_f(v):
    return float(fmt_float(v))


def _pretty(kind, v):
    """decompile's JSON-safe field form -> editor-friendly YAML form."""
    if kind == G.F32:
        return _short_f(v)
    if kind in (G.SLOT_STR, G.SLOT_INT):
        return {s: x for s, x in v}
    if kind == G.SLOT_F32:
        return {s: _short_f(x) for s, x in v}
    if kind == G.CAP:
        return {s: [name, _short_f(val)] for s, name, val in v}
    if kind == G.AREA:
        return {col: rows for col, rows in v}           # column -> rows
    # RES stays a list of [ore, amount] pairs: retail can list the same ore
    # twice (parallel slots), which a mapping would silently collapse.
    return v                                             # int/str/flag/res/depend/bank_range/source4


def _plain(kind, v):
    """editor-friendly YAML form -> decompile's JSON-safe form (compile re-quantizes f32)."""
    if kind in (G.SLOT_STR, G.SLOT_INT, G.SLOT_F32):
        return [[int(s), x] for s, x in v.items()]
    if kind == G.CAP:
        return [[int(s), w[0], w[1]] for s, w in v.items()]
    if kind == G.AREA:
        return [[int(col), rows] for col, rows in v.items()]
    return v                                             # int/str/flag/res/depend/bank_range/source4


def _objs(d, cls):
    """Class objects with an explicit 0-based index + editor-friendly fields."""
    rev = _reverse_map(cls)
    out = []
    for i, o in enumerate(d["classes"][cls]):
        rec = {"name": o["name"], "index": i}
        for k, v in o.items():
            if k != "name":
                rec[k] = _pretty(rev[k][0], v)
        out.append(rec)
    return out


# Subtrees/files write_tree owns and fully regenerates. Faction classes emit
# dynamically-named files (units/alien.yaml, .../other.yaml, …), so a re-decompile
# whose object names bucket differently (e.g. after applying English aliases) must
# not leave the previous run's files behind — read_tree globs recursively and would
# merge the stale copies, doubling objects. Everything else outside this set
# (notably aliases.yaml at the tree root) is preserved.
_MANAGED_DIRS = ("constants", "sprites", "localization", "anims", "tech",
                 "world", "units", "buildings", "weapons")
_MANAGED_FILES = ("modifiers.yaml", "weapons.yaml")


def _clean_managed(cfg_dir):
    for d in _MANAGED_DIRS:
        shutil.rmtree(os.path.join(cfg_dir, d), ignore_errors=True)
    for f in _MANAGED_FILES:
        try:
            os.remove(os.path.join(cfg_dir, f))
        except OSError:
            pass


def write_tree(model, cfg_dir: str, aliases=None):
    factions = _wire_factions(model, aliases)
    if aliases is not None:
        model = aliases.to_english(model)
    _clean_managed(cfg_dir)
    hdr = _HEADER_TOP + (_HEADER_ALIAS if aliases is not None else _HEADER_WIRE)
    d = D.decompile(model)

    _dump(cfg_dir, "constants/defines.yaml", {"defines": dict(model.defines)}, hdr)
    _dump(cfg_dir, "modifiers.yaml", {"modifiers": d["globals"]}, hdr)
    _dump(cfg_dir, "sprites/def_banks.yaml", {"def_banks": [list(x) for x in d["def_banks"]]}, hdr)
    _dump(cfg_dir, "sprites/banks.yaml", {"banks": d["banks"]}, hdr)
    _dump(cfg_dir, "sprites/icons.yaml", {"icons": dict(model.icons)}, hdr)
    _dump(cfg_dir, "localization/text_ru.yaml", {"texts": dict(model.texts)}, hdr)

    # single-file classes
    for cls, rel in (("ANIM", "anims/anims.yaml"), ("WEAPON", "weapons.yaml"),
                     ("PROGRESS", "tech/inventions.yaml"), ("UPGRADE", "tech/upgrades.yaml"),
                     ("PROJECT", "tech/projects.yaml"), ("SYSTEM", "world/systems.yaml"),
                     ("PLANET", "world/planets.yaml"), ("TREE", "world/trees.yaml"),
                     ("STONE", "world/stones.yaml")):
        objs = _objs(d, cls)
        if objs:
            _dump(cfg_dir, rel, {CLASS2KEY[cls]: objs}, hdr)

    # faction-split classes (faction from the wire name when aliased)
    for cls, sub in (("UNIT", "units"), ("BUILDING", "buildings")):
        buckets = defaultdict(list)
        for i, rec in enumerate(_objs(d, cls)):
            fac = factions[cls][i] if factions else _faction(rec["name"])
            buckets[fac].append(rec)
        for fac, recs in buckets.items():
            _dump(cfg_dir, f"{sub}/{fac}.yaml", {sub: recs}, hdr)


# Classes exploded into one-file-per-object in the per-object layout, and where
# their files land. Faction-split classes get a <faction>/ subdir; weapons are
# not factional so they go flat under weapons/. These are exactly the classes
# that own foldable resources (they carry the art/icon fields).
_EXPLODE = {"UNIT": ("units", True), "BUILDING": ("buildings", True),
            "WEAPON": ("weapons", False)}


def _safe_filename(name):
    """A filesystem-safe stem for an object name (names are ASCII cfg tokens, but
    guard anyway). Placement is cosmetic, so the exact stem does not matter —
    only that distinct objects get distinct files (deduped by the caller)."""
    stem = "".join(c if (c.isalnum() or c in "._-") else "_" for c in name)
    return stem.strip("._") or "obj"


def write_tree_per_object(model, cfg_dir: str, aliases=None):
    """Per-object layout: emit one file per UNIT/BUILDING/WEAPON at
    ``<class>/<faction>/<name>.yaml``, with the anims and icons it *exclusively*
    owns (fan-in 1, per :func:`refgraph.ownership`) folded into that file.
    Resources shared by >=2 objects, or referenced only by code, stay in the
    default class files (``anims/anims.yaml``, ``sprites/icons.yaml``).

    This only changes *where* content is written — :func:`read_tree` globs by
    top-level key regardless — so it round-trips identically to the class layout
    (layout is cosmetic). Each resource is emitted exactly once (folded XOR
    default) so the recursive read never sees a duplicate.
    """
    from . import refgraph as RG
    factions = _wire_factions(model, aliases)
    if aliases is not None:
        model = aliases.to_english(model)
    _clean_managed(cfg_dir)
    hdr = _HEADER_TOP + (_HEADER_ALIAS if aliases is not None else _HEADER_WIRE)
    d = D.decompile(model)

    # resource (ns, name) -> sole owner (cls, name), but only when that owner is
    # an exploded class (so we never fold into a file we don't emit).
    owner_of = {}
    for o in RG.ownership(model, ("anims", "icons")):
        if o.fanin == 1:
            (oc, on), = o.owners
            if oc in _EXPLODE:
                owner_of[(o.ns, o.name)] = (oc, on)

    # split anims (class objects) and icons (flat name->id) into folded vs default
    anim_by_owner, default_anims = defaultdict(list), []
    for a in _objs(d, "ANIM"):
        ow = owner_of.get(("anims", a["name"]))
        (anim_by_owner[ow] if ow else default_anims).append(a)
    icon_by_owner, default_icons = defaultdict(dict), {}
    for name, val in model.icons:
        ow = owner_of.get(("icons", name))
        if ow:
            icon_by_owner[ow][name] = val
        else:
            default_icons[name] = val

    # flat sections (icons reduced to the non-folded remainder)
    _dump(cfg_dir, "constants/defines.yaml", {"defines": dict(model.defines)}, hdr)
    _dump(cfg_dir, "modifiers.yaml", {"modifiers": d["globals"]}, hdr)
    _dump(cfg_dir, "sprites/def_banks.yaml", {"def_banks": [list(x) for x in d["def_banks"]]}, hdr)
    _dump(cfg_dir, "sprites/banks.yaml", {"banks": d["banks"]}, hdr)
    _dump(cfg_dir, "sprites/icons.yaml", {"icons": default_icons}, hdr)
    _dump(cfg_dir, "localization/text_ru.yaml", {"texts": dict(model.texts)}, hdr)
    if default_anims:
        _dump(cfg_dir, "anims/anims.yaml", {"anims": default_anims}, hdr)

    # non-exploded classes keep their single default file
    for cls, rel in (("PROGRESS", "tech/inventions.yaml"), ("UPGRADE", "tech/upgrades.yaml"),
                     ("PROJECT", "tech/projects.yaml"), ("SYSTEM", "world/systems.yaml"),
                     ("PLANET", "world/planets.yaml"), ("TREE", "world/trees.yaml"),
                     ("STONE", "world/stones.yaml")):
        objs = _objs(d, cls)
        if objs:
            _dump(cfg_dir, rel, {CLASS2KEY[cls]: objs}, hdr)

    # one file per exploded object, folded resources inlined. Ownership is keyed
    # by object *name*, and some names repeat (e.g. BUILDING N_alien_Chatka x8);
    # such duplicates are one owner, so their shared resources fold into the FIRST
    # file only (folded_done), never replicated across the siblings.
    folded_done = set()
    for cls, (sub, factioned) in _EXPLODE.items():
        used = defaultdict(set)  # per-directory filename-collision guard
        for i, rec in enumerate(_objs(d, cls)):
            owner = (cls, rec["name"])
            doc = {CLASS2KEY[cls]: [rec]}
            if owner not in folded_done:
                folded_done.add(owner)
                if anim_by_owner.get(owner):
                    doc["anims"] = anim_by_owner[owner]
                if icon_by_owner.get(owner):
                    doc["icons"] = dict(icon_by_owner[owner])
            if factioned:
                fac = factions[cls][i] if factions else _faction(rec["name"])
                reldir = f"{sub}/{fac}"
            else:
                reldir = sub
            seen = used[reldir]
            stem = _safe_filename(rec["name"])
            fn, i = stem, 2
            while fn in seen:            # distinct objects, same stem -> suffix
                fn, i = f"{stem}_{i}", i + 1
            seen.add(fn)
            _dump(cfg_dir, f"{reldir}/{fn}.yaml", doc, hdr)


class IndexDensityError(ValueError):
    """A class's object ``index`` values aren't a dense 0..N-1 permutation."""


def _check_index_density(classes):
    """Each class's indices must be exactly {0..N-1}, once each (so sorting by
    index restores the intended order and count). Returns a list of problems."""
    problems = []
    for cls, objs in classes.items():
        idx = [o.get("index") for o in objs]
        if any(i is None for i in idx):
            problems.append(f"{cls}: {sum(i is None for i in idx)} object(s) missing 'index'")
            continue
        n = len(objs)
        counts = Counter(idx)
        dups = sorted(i for i, c in counts.items() if c > 1)
        if dups:
            problems.append(f"{cls}: duplicate index {dups}")
        missing = sorted(set(range(n)) - set(idx))
        extra = sorted(i for i in set(idx) if i < 0 or i >= n)
        if missing or extra:
            problems.append(f"{cls}: {n} objects but indices aren't dense 0..{n - 1} "
                            f"(missing {missing}, out-of-range {extra})")
    return problems


def read_tree(cfg_dir: str, aliases=None):
    acc = {"defines": {}, "modifiers": {}, "def_banks": [], "icons": {},
           "banks": [], "texts": {}, "classes": defaultdict(list)}
    for path in sorted(glob.glob(os.path.join(cfg_dir, "**", "*.yaml"), recursive=True)):
        if os.path.basename(path) == "aliases.yaml":
            continue  # the alias table lives in the tree but is not config content
        doc = yaml.safe_load(open(path, encoding="utf-8")) or {}
        for key, val in doc.items():
            if key in ("defines", "icons", "texts", "modifiers"):
                acc[key].update(val)
            elif key == "def_banks":
                acc["def_banks"].extend(val)
            elif key == "banks":
                acc["banks"].extend(val)
            elif key in KEY2CLASS:
                acc["classes"][KEY2CLASS[key]].extend(val)
            else:
                raise ValueError(f"{path}: unknown top-level key {key!r}")

    problems = _check_index_density(acc["classes"])
    if problems:
        raise IndexDensityError("index-density errors in the YAML sources:\n  "
                                + "\n  ".join(problems))

    data = {
        "defines": [[k, v] for k, v in acc["defines"].items()],
        "def_banks": [list(x) for x in acc["def_banks"]],
        "icons": [[k, v] for k, v in acc["icons"].items()],
        "texts": [[k, v] for k, v in acc["texts"].items()],
        "banks": acc["banks"],
        "globals": acc["modifiers"],
        "classes": {},
    }
    for cls in KEY2CLASS.values():
        rev = _reverse_map(cls)
        objs = sorted(acc["classes"].get(cls, []), key=lambda o: o["index"])
        recs = []
        for o in objs:
            rec = {"name": o["name"]}
            for k, v in o.items():
                if k not in ("name", "index"):
                    rec[k] = _plain(rev[k][0], v)
            recs.append(rec)
        data["classes"][cls] = recs
    model = D.compile_(data)
    if aliases is not None:
        model = aliases.to_wire(model)
    return model
