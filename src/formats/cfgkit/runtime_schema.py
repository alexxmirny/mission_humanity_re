"""Generate the native CFG schema from cfgkit's grammar metadata.

Run ``python -m src.formats.cfgkit.runtime_schema --output PATH``; add
``--check`` to compare an existing generated file without modifying it.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from . import emit, grammar as G

_KIND = {
    G.INT: "Int", G.F32: "F32", G.STR: "Str", G.FLAG: "Flag",
    G.SLOT_STR: "SlotStr", G.SLOT_INT: "SlotInt", G.SLOT_F32: "SlotF32",
    G.CAP: "Cap", G.RES: "Res", G.DEPEND: "Depend", G.AREA: "Area",
    G.BANK_RANGE: "BankRange", G.SOURCE4: "Source4", G.BANK_SPRITE: "BankSprite",
}


def _q(value):
    return json.dumps(str(value), ensure_ascii=True)


def render():
    lines = ["// Generated by cfgkit.runtime_schema; do not edit.", "#pragma once",
             '#include "mh_cfg_schema_types.h"',
             "namespace mh::mods::cfg::schema {"]

    def table(typ, name, rows):
        lines.append(f"inline constexpr {typ} {name}[] = {{")
        lines.extend("    {" + ", ".join(row) + "}," for row in rows)
        lines.append("};")

    table("Keyword", "keywords", (
        (_q(cls), _q(kw), "Kind::" + _KIND[kind], _q(field))
        for cls, entries in G.CLASS_GRAMMAR.items()
        for kw, (kind, field) in entries.items()))
    seeds = []
    for cls, fields in G.DEFAULT_OVERLAY.items():
        for field, value in fields.items():
            if isinstance(value, dict):
                values = sorted(value.items())
            elif isinstance(value, list):
                values = enumerate(value)
            else:
                values = [(-1, value)]
            for slot, element in values:
                seeds.append((_q(cls), _q(field), str(slot), _q(element)))
    table("Seed", "seeds", seeds)
    table("Modifier", "modifiers", ((_q(kw), "Kind::" + _KIND[kind], repr(G.MODIFIER_DEFAULTS[kw]))
                                      for kw, kind in G.MODIFIERS.items()))
    lines.append("inline constexpr const char* class_order[] = {" +
                 ", ".join(_q(cls) for cls in emit.CLASS_ORDER) + "};")
    table("Cap", "caps", ((_q(cls), _q(field), _q(mode), str(limit))
                          for (cls, field), (mode, limit) in G.CAPS.items()))
    table("Ref", "refs", ((_q(cls), _q(field), _q(universe))
                          for (cls, field), universe in G.REF.items()))
    table("Domain", "domains", ((_q(cls), _q(field), str(lo), str(hi))
                                for (cls, field), (lo, hi) in G.DOMAIN.items()))
    table("Transform", "transforms", ((_q(cls), _q(field), _q(mul), _q(add),
                                      "true" if integer else "false")
                                     for cls, field, mul, add, integer in G.TRANSFORMS))
    table("HousingReason", "housing_reasons", ((str(reason), str(alien), str(human))
                                                 for reason, alien, human in G.HOUSING_REASONS))
    table("BuildingKind", "building_kinds", ((_q(name), str(value))
                                             for name, value in G.BUILDING_KINDS))
    lines.append("}  // namespace mh::mods::cfg::schema")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        if not args.output.exists() or args.output.read_bytes() != content.encode("utf-8"):
            print(f"schema differs: {args.output}")
            return 1
    else:
        args.output.write_bytes(content.encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
