//
// imgui_d3dcompile.cpp -- PT-GFX4: the D3DCompile that the vendored imgui_impl_dx11.cpp links against.
//
// THE PROBLEM. Dear ImGui's DX11 backend compiles its two tiny shaders at runtime with D3DCompile()
// and carries `#pragma comment(lib, "d3dcompiler")`, i.e. a LINK-TIME import of d3dcompiler_47.dll.
// mh.dll must not grow one: it loads through the msvfw32 proxy before the exe's entry point, so a
// missing or wrong-version d3dcompiler would fail PROCESS LOAD (0xC0000135) for every player, d3d11
// backend or not -- and the presenter it serves already loads d3d11.dll on demand for exactly that
// reason (backend_d3d11.cpp's "NO LINK-TIME DEPENDENCY").
//
// THE CHOICE: PRECOMPILED BLOBS, SUPPLIED BY DEFINING D3DCompile HERE -- the vendored backend is not
// edited at all. The linker resolves the backend's `D3DCompile` reference to this definition (an
// object file beats a library), and mh.vcxproj / mh_nettest.vcxproj list d3dcompiler.lib under
// IgnoreSpecificDefaultLibraries so the pragma cannot pull the import library in either -- if this
// file were ever dropped from a project the link FAILS instead of silently importing the DLL.
// Keeping imgui_impl_dx11.cpp byte-identical to upstream is what makes an ImGui update a plain
// re-copy.
//
// WHICH SHADER. The backend's source strings are identified by target + an FNV-1a hash of the exact
// bytes it passes (the C literal after line splicing). A match returns fxc bytecode compiled offline
// from that very text; no match (an ImGui update changed a shader and nobody regenerated the blobs)
// falls back to d3dcompiler_47.dll resolved with LoadLibrary/GetProcAddress, and logs once -- so an
// update degrades to "needs d3dcompiler_47 on the machine", never to a broken overlay or a load-time
// import. Failing both, it returns E_FAIL and the backend's own error path leaves the overlay off.
//
// REGENERATE (after re-vendoring ImGui): extract the two literals `vertexShader` / `pixelShader` from
// imgui_impl_dx11.cpp's ImGui_ImplDX11_CreateDeviceObjects, remove each backslash-newline (C
// translation phase 2), hash the resulting bytes (FNV-1a 32) into K_VS_HASH / K_PS_HASH, and
//   fxc /nologo /T vs_4_0 /E main /Fh vs.h /Vn g_imgui_vs vertexShader.hlsl
//   fxc /nologo /T ps_4_0 /E main /Fh ps.h /Vn g_imgui_ps pixelShader.hlsl
// (Windows SDK 10.0.22621.0 x86 fxc, the same one backend_d3d11.cpp's header names), then paste the
// byte arrays below. Measured for ImGui v1.92.9: vs 733 source bytes -> 876 bytecode bytes, ps 401 ->
// 660.
//
