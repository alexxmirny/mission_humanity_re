unsigned fnv1a(const void *p, size_t n) {
    const unsigned char *b = static_cast<const unsigned char *>(p);
    unsigned             h = 0x811c9dc5u;
    for (size_t i = 0; i < n; ++i) {
        h ^= b[i];
        h *= 0x01000193u;
    }
    return h;
}

